function oddOrEven(number) {
    if (number % 2 === 0) {
        return "ლუწი";
    } else {
        return "კენტი";
    }
}

// 2
function square(number) {
    return number ** 2;
}

// 3
function area(length, width) {
    return length * width;
}

// 4
function isPositive(number) {
    return number > 0;
}

